const ASHI_ITEMS = ['lap', 'turn', 'straight', 'ex'];  // 一周, まわり足, 直線, 展示

/**
 * 汎用の計算。
 * @param {number|string} jcd 場コード（1〜24）
 * @param {Array<{waku:number, lap?:number|null, turn?:number|null, straight?:number|null, ex:number}>} boats
 * @returns {Array<{waku, score, rank, z:number[]}>} 入力と同じ並び
 */
function ashiScore(jcd, boats) {
  const code = Number(jcd);
  const w = ASHI_CONFIG.weights[code] || ASHI_CONFIG.defaultWeights;
  const corr = ASHI_CONFIG.corrVenue[code] || ASHI_CONFIG.corrCommon;
  const z = boats.map(() => [0, 0, 0, 0]);
  ASHI_ITEMS.forEach((k, j) => {
    const xs = boats.map(b => (b[k] == null || isNaN(b[k])) ? null
      : Math.round((Number(b[k]) + corr[b.waku][j]) * 100) / 100);   // 補正後を小数第2位に
    const v = xs.filter(x => x != null);
    if (v.length < 2) return;
    const mu = v.reduce((a, b) => a + b, 0) / v.length;
    const sd = Math.sqrt(v.reduce((a, b) => a + (b - mu) ** 2, 0) / (v.length - 1));
    if (!(sd > 0)) return;
    xs.forEach((x, i) => { if (x != null) z[i][j] = (mu - x) / sd; });
  });
  const out = boats.map((b, i) => ({
    waku: b.waku, z: z[i],
    score: z[i].reduce((a, zz, j) => a + w[j] * zz, 0),
  }));
  [...out].sort((a, b) => b.score - a.score || a.waku - b.waku).forEach((o, r) => { o.rank = r + 1; });
  return out;
}

/**
 * 艇読みAIのレースデータ（race.jcd, race.before.boats[waku].exTime, race.before.ori）から計算する。
 * オリジナル展示がない場・項目が足りない場もそのまま計算できる（ない項目は全艇 z=0）。
 * @returns {null | {jcd, verified, sep, items, note, boats:{[waku]:{score, rank, z}}}}
 */
function ashiFromRace(race) {
  const bf = race && race.before;
  if (!bf || !bf.boats) return null;
  const ori = bf.ori && bf.ori.items ? bf.ori : null;
  const idx = {};
  const notes = [];
  if (ori) ori.items.forEach((nm, j) => {
    if (nm === '一周') idx.lap = j;
    else if (nm === '半周ラップ') { idx.lap = j; if (Number(race.jcd) !== 1) notes.push('一周の代わりに半周ラップを使用（未検証）'); }
    else if (nm === 'まわり足') idx.turn = j;
    else if (nm === '直線') idx.straight = j;
  });
  if (!ori) notes.push('オリジナル展示なし（展示タイムのみ）');
  else if (idx.straight == null) notes.push('直線の計測なし');
  const boats = [];
  for (let w = 1; w <= 6; w++) {
    const q = bf.boats[w] || bf.boats[String(w)];
    if (!q || q.exTime == null) continue;           // 欠場・展示タイムなしは外す
    const ov = ori ? (ori.boats[w] || ori.boats[String(w)] || []) : [];
    const g = k => (idx[k] == null ? null : (ov[idx[k]] == null ? null : Number(ov[idx[k]])));
    boats.push({waku: w, lap: g('lap'), turn: g('turn'), straight: g('straight'), ex: Number(q.exTime)});
  }
  if (boats.length < 2) return null;
  const jcd = Number(race.jcd);
  const res = {};
  ashiScore(jcd, boats).forEach(o => { res[o.waku] = {score: o.score, rank: o.rank, z: o.z}; });
  const verified = ASHI_CONFIG.weights[jcd] != null;
  return {
    jcd, verified, sep: ASHI_CONFIG.sep[jcd] ?? null,
    items: ASHI_ITEMS.filter(k => boats.some(b => b[k] != null)),
    note: (verified ? '' : '未検証の場（戸田新式＋共通補正）') + (notes.length ? (verified ? '' : '・') + notes.join('・') : ''),
    boats: res,
  };
}

